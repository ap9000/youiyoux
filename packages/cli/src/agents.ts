/**
 * The agent layer, generated from one source (contracts, tokens, rules):
 *   AGENTS.md block   always-on orchestration, ≤ 40 lines
 *   DESIGN.md         look and feel, Google DESIGN.md format (frontmatter + narrative)
 *   SKILL.md          procedures: build a screen, fix a violation, find usages, propose a change
 *   youi-rules/*.yml  the rules that plain ast-grep can enforce on its own
 * Each rule therefore exists three ways: prose for people, an instruction for
 * agents, and an executable check.
 */
import { COMMAND, SUBCOMMANDS } from "./command.ts";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";
import { executionLabel, MCP_TOOLS, type ComponentContract, type RuleSpec } from "@youiyoux/core";
import { cssValue, type ResolvedToken, type TokenBuild } from "@youiyoux/tokens";
import { importLine, ruleCapability, type Project } from "@youiyoux/scanner";

export const BLOCK_BEGIN = "<!-- youi:begin -->";
export const BLOCK_END = "<!-- youi:end -->";
/** `youiyoux agents install`'s block in AGENTS.md and CLAUDE.md; it carries the check --diff line when it is there. */
export const RULE_BEGIN = "<!-- youi:agents:begin -->";
export const RULE_END = "<!-- youi:agents:end -->";
/** The heading of the repo-mode block `youiyoux hooks install` writes (repoAgentsBlock), as opposed to sync's design-language block. */
export const REPO_BLOCK_HEADING = "## UI context and verification (YouIyouX)";
export const GENERATED_MARK = "@generated by youi";
/** The one rule every agent gets, in AGENTS.md and CLAUDE.md (`youiyoux agents install`), the synced AGENTS.md block and SKILL.md. */
export const FIND_FIRST_RULE = "Before creating a UI component, call `ui_find_component` (MCP server `youiyoux`) with the need in words (\"dismissible alert\", \"primary button with icon\"): reuse the existing component it names, with its import and props; only when it says nothing fits, start where it says.";

/** Committed instructions must not depend on the machine that generated them. */
export function portableYoui(root?: string): { run: string; setup: string } {
  if (root) {
    try {
      const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
      if (pkg.dependencies?.["@youiyoux/cli"] || pkg.devDependencies?.["@youiyoux/cli"]) {
        return { run: `npx --no-install ${COMMAND}`, setup: "First install this repo's dependencies with its package manager." };
      }
    } catch { /* No package manifest: use the installed bin. */ }
  }
  return { run: `npx -y ${COMMAND}`, setup: "Run from the repo root." };
}

const BARE = new RegExp(`(?<![\\w@/.-]|npx (?:-y |--no-install ))${COMMAND} (?=(?:${SUBCOMMANDS.join("|")})\\b)`, "g");

/** Agent-facing text with every youiyoux command in the portable form (npx), never a bare bin an agent's shell may not have. */
export function viaNpx(text: string, root?: string): string {
  return text.replace(BARE, `${portableYoui(root).run} `);
}

export function diffInstruction(root?: string): string {
  const { run, setup } = portableYoui(root);
  return `- ${setup} After UI edits, run \`${run} check --diff\` (\`--json\` for data): it lists what your change adds that near-duplicates an existing component, hardcodes a value a token holds, or imports an element from a library other than the project's choice, each with its fix. Apply each fix.`;
}
export const DIFF_INSTRUCTION = diffInstruction();

export function repoAgentsBlock(root?: string): string {
  return viaNpx([BLOCK_BEGIN, REPO_BLOCK_HEADING, "", diffInstruction(root), "- Run `youiyoux init --design <dir>` to connect design-system rules; repository inference works without it.", BLOCK_END].join("\n"), root);
}

function generatedNote(project: Project): string {
  const s = project.system.config;
  return `${GENERATED_MARK} from the ${s.name} design language v${s.version}. Do not edit: change the design language and run \`youiyoux sync\`.`;
}

/** Rules `youiyoux check` actually runs. */
const enforced = (rules: readonly RuleSpec[]): RuleSpec[] => rules.filter((r) => ruleCapability(r).state === "enforced");
/** Rules agents still follow though nothing checks them: advisory prose, and checks this youi cannot run. */
const unchecked = (rules: readonly RuleSpec[]): RuleSpec[] => rules.filter((r) => ["advisory", "unsupported"].includes(ruleCapability(r).state));

export interface UnknownToolMention {
  readonly rule: string;
  readonly tool: string;
}

/** Tool names in the agent text of rules copied into AGENTS.md and SKILL.md (checked or not) that the MCP server does not expose. */
export function unknownToolMentions(project: Project): UnknownToolMention[] {
  const known = new Set<string>(MCP_TOOLS);
  return [...enforced(project.system.rules), ...unchecked(project.system.rules)].flatMap((r) => [...new Set(r.agent.match(/\b(?:system|library|discover|index|youi|ui)_[a-z_]+\b/g) ?? [])].filter((tool) => !known.has(tool)).map((tool) => ({ rule: r.id, tool })));
}

function enumSummary(contract: ComponentContract): string {
  return Object.entries(contract.props)
    .filter(([, spec]) => spec.type === "enum")
    .map(([name, spec]) => `${name}: ${(spec as { values: string[] }).values.join("|")}`)
    .join("; ");
}

/** Where components are imported from, for prose: the alias, or componentsDir by a relative path. */
function importHint(config: Project["config"]): string {
  return config.importFrom ? `\`${config.importFrom}\`` : `\`${config.componentsDir}\` (by a relative path from your file)`;
}

/* ----------------------------------------------------------------- AGENTS.md */

export function agentsBlock(project: Project): string {
  const { config, system } = project;
  const names = system.components.map((c) => c.contract.name).join(", ");
  const from = importHint(config);
  const lines = [
    BLOCK_BEGIN,
    `<!-- ${generatedNote(project)} -->`,
    `## Design language: ${system.config.name} (YouIyouX)`,
    "",
    `This project's UI follows ${system.config.name} v${system.config.version}. Exact contracts live in YouIyouX: look them up, never guess.`,
    "",
    "- **Build only with the System.** System elements are approved: the components, tokens and rules below, looked up with `system_*` tools (MCP server `youiyoux`) or `youiyoux show`. Library items (`lib:` ids, `library_*` tools, `youiyoux library`) are ingested references, not approved: never import, copy or restyle code from one. To use one, draft a request with `library_request` (or `youiyoux library request <id>`), put it in your summary, and keep building with the System.",
    `- ${FIND_FIRST_RULE}`,
    `- Build UI from the owned components, imported from ${from}: ${names}.`,
    "- Before using a component's props, call `system_get_component` or run `youiyoux show <component>`; use only the listed values.",
    ...enforced(system.rules).map((r) => `- ${r.agent}`),
    ...unchecked(system.rules).map((r) => `- ${r.agent} (not checked by \`youiyoux check\`: follow it yourself)`),
    `- Never edit files marked \`${GENERATED_MARK}\` (\`${config.outputs.dir}/*\`, ${config.agents.designMd}, the youiyoux skill). Change the design language and run \`youiyoux sync\`.`,
    `- Owned component files in \`${config.componentsDir}\` may be edited; \`youiyoux sync\` 3-way merges upstream changes into them and reports drift.`,
    "- After changing a component, call `ui_render` with its file (or run `youiyoux render <file>`) and look at the images: light and dark, desktop and phone, its accessibility issues and the diff against the base. Fix what it reports.",
    "- People pin comments and change requests to components on captured screens. Before UI work, call `requests_list` (or run `youiyoux requests`); after making a requested change, call `request_addressed` with what you changed (file:line). Ask with `request_reply` when one is unclear. A person closes requests, never an agent.",
    "- Before you finish, run `youiyoux check`; it must report 0 errors.",
    diffInstruction(project.root),
    "- To change the System itself (a token, a prop, a rule), run `youiyoux plan` (or `system_plan`) and propose it. Agents never approve, publish or merge design changes.",
    `- More: ${config.agents.designMd} (look and feel), \`${config.agents.skillDir}/SKILL.md\` (procedures), MCP server \`youiyoux\` (exact JSON).`,
    BLOCK_END,
  ];
  return viaNpx(lines.join("\n"), project.root);
}

/** Replace the managed block in `existing` (or append it), leaving every other line untouched. */
export function upsertBlock(existing: string | null, block: string): string {
  if (!existing) return `${block}\n`;
  const start = existing.indexOf(BLOCK_BEGIN);
  const end = existing.indexOf(BLOCK_END);
  if (start >= 0 && end > start) return `${existing.slice(0, start)}${block}${existing.slice(end + BLOCK_END.length)}`;
  return `${existing.replace(/\s*$/, "")}\n\n${block}\n`;
}

/* ----------------------------------------------------------------- DESIGN.md */

function key(token: ResolvedToken): string {
  return token.id.split(".").slice(1).join("-");
}

function frontmatter(project: Project, build: TokenBuild): Record<string, unknown> {
  const byGroup = (group: string) => build.tokens.filter((t) => t.id.startsWith(`${group}.`));
  const colors: Record<string, string> = {};
  for (const t of byGroup("color")) {
    colors[key(t)] = cssValue(t.type, t.light);
    const dark = cssValue(t.type, t.dark);
    if (dark !== colors[key(t)]) colors[`${key(t)}-dark`] = dark;
  }
  const typography: Record<string, Record<string, string | number>> = {};
  for (const t of byGroup("typography")) {
    const v = t.light as { fontFamily: string[] | string; fontSize: { value: number; unit: string }; fontWeight: number; lineHeight: number; letterSpacing?: { value: number; unit: string } };
    typography[key(t)] = {
      fontFamily: cssValue("fontFamily", v.fontFamily),
      fontSize: `${v.fontSize.value}${v.fontSize.unit}`,
      fontWeight: v.fontWeight,
      lineHeight: v.lineHeight,
      ...(v.letterSpacing ? { letterSpacing: `${v.letterSpacing.value}${v.letterSpacing.unit}` } : {}),
    };
  }
  const dims = (group: string): Record<string, string> => Object.fromEntries(byGroup(group).map((t) => [key(t), cssValue(t.type, t.light)]));
  const ref = (tokenId: string): string | null => {
    const id = tokenId.replace(/^youi:[a-z-]+\/token\//, "");
    const [group, ...rest] = id.split(".");
    const name = rest.join("-");
    return group === "color" ? `{colors.${name}}` : group === "radius" ? `{rounded.${name}}` : group === "typography" ? `{typography.${name}}` : null;
  };
  const property: Record<string, string> = { bg: "backgroundColor", fg: "textColor", radius: "rounded", text: "typography", border: "borderColor" };
  const components: Record<string, Record<string, string>> = {};
  for (const { contract } of project.system.components) {
    const base = contract.name.toLowerCase();
    for (const [binding, tokenId] of Object.entries(contract.tokens)) {
      const [prop, variant] = binding.split(".");
      const field = property[prop ?? ""];
      const value = ref(tokenId);
      if (!field || !value) continue;
      const name = variant && variant !== "default" ? `${base}-${variant}` : base;
      components[name] = { ...components[name], [field]: value };
    }
  }
  return {
    name: project.system.config.name,
    description: project.system.config.description,
    colors,
    typography,
    rounded: dims("radius"),
    spacing: Object.fromEntries(Object.entries(dims("space"))),
    components,
  };
}

function componentsSection(project: Project): string {
  const rows = project.system.components.map(({ contract }) => `| ${contract.name} | \`${importLine(project, contract)}\` | ${enumSummary(contract) || "—"} | ${contract.summary} |`);
  return ["## Components (contracts)", "", "| Component | Import | Values | Use |", "| --- | --- | --- | --- |", ...rows].join("\n");
}

function rulesSection(project: Project): string {
  const rows = project.system.rules.filter((r) => r.severity !== "off").map((r) => `| ${r.title} | ${r.severity} | ${executionLabel(ruleCapability(r))} | ${r.statement} |`);
  return ["## Rules", "", "| Rule | Severity | Enforcement | Statement |", "| --- | --- | --- | --- |", ...rows].join("\n");
}

export function designMd(project: Project, build: TokenBuild, narrative: string | null): string {
  const fm = stringify(frontmatter(project, build), { lineWidth: 0 }).trimEnd();
  const lookup = [
    "## Look it up",
    "",
    "- Build only with System elements. Exact contracts, tokens and rules: MCP server `youiyoux` (`system_get_component`, `system_get_tokens`, `system_get_rules`) or `youiyoux show <component>`.",
    "- Where something is used, screen by screen: `youiyoux where <component> [--route <route>]` or `system_where_used`.",
    "- Library items (`lib:` ids, `library_search`) are unapproved references: never build with them; request adoption with `library_request`.",
    "- Before finishing UI work: `youiyoux check`.",
  ].join("\n");
  const body = (narrative ?? `# Design System: ${project.system.config.name}\n`).replace(/^<!--[\s\S]*?-->\s*/, "").trim();
  return `---\n${fm}\n---\n\n<!-- ${viaNpx(generatedNote(project), project.root)} -->\n\n${body}\n\n${componentsSection(project)}\n\n${rulesSection(project)}\n\n${viaNpx(lookup, project.root)}\n`;
}

