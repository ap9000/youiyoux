/**
 * The agent layer, generated from one source (contracts, tokens, rules):
 *   AGENTS.md block   always-on orchestration, ≤ 40 lines
 *   DESIGN.md         look and feel, Google DESIGN.md format (frontmatter + narrative)
 *   SKILL.md          procedures: build a screen, fix a violation, find usages, propose a change
 *   youi-rules/*.yml  the rules that plain ast-grep can enforce on its own
 * Each rule therefore exists three ways: prose for people, an instruction for
 * agents, and an executable check.
 */
import { stringify } from "yaml";
import type { ComponentContract, RuleSpec } from "@youiyoux/core";
import { cssValue, type ResolvedToken, type TokenBuild } from "@youiyoux/tokens";
import { importLine, type Project } from "@youiyoux/scanner";

export const BLOCK_BEGIN = "<!-- youi:begin -->";
export const BLOCK_END = "<!-- youi:end -->";
export const GENERATED_MARK = "@generated by youi";

function generatedNote(project: Project): string {
  const s = project.system.config;
  return `${GENERATED_MARK} from the ${s.name} design language v${s.version}. Do not edit: change the design language and run \`youi sync\`.`;
}

const enforced = (rules: readonly RuleSpec[]): RuleSpec[] => rules.filter((r) => r.severity !== "off" && r.check.engine !== "advisory");

function enumSummary(contract: ComponentContract): string {
  return Object.entries(contract.props)
    .filter(([, spec]) => spec.type === "enum")
    .map(([name, spec]) => `${name}: ${(spec as { values: string[] }).values.join("|")}`)
    .join("; ");
}

/* ----------------------------------------------------------------- AGENTS.md */

export function agentsBlock(project: Project): string {
  const { config, system } = project;
  const names = system.components.map((c) => c.contract.name).join(", ");
  const from = config.importFrom ?? config.componentsDir;
  const lines = [
    BLOCK_BEGIN,
    `<!-- ${generatedNote(project)} -->`,
    `## Design language: ${system.config.name} (YouIyouX)`,
    "",
    `This project's UI follows ${system.config.name} v${system.config.version}. Exact contracts live in YouIyouX: look them up, never guess.`,
    "",
    `- Build UI from the owned components, imported from \`${from}\`: ${names}.`,
    "- Before using a component's props, call `youi_get_component` (MCP server `youiyoux`) or run `youi show <component>`; use only the listed values.",
    ...enforced(system.rules).map((r) => `- ${r.agent}`),
    `- Never edit files marked \`${GENERATED_MARK}\` (\`${config.outputs.dir}/*\`, ${config.agents.designMd}, the youiyoux skill). Change the design language and run \`youi sync\`.`,
    `- Owned component files in \`${config.componentsDir}\` may be edited; \`youi sync\` 3-way merges upstream changes into them and reports drift.`,
    "- Before you finish, run `youi check`; it must report 0 errors.",
    "- To change the system itself (a token, a prop, a rule), run `youi plan` and propose it. Agents never approve, publish or merge design changes.",
    `- More: ${config.agents.designMd} (look and feel), \`${config.agents.skillDir}/SKILL.md\` (procedures), MCP server \`youiyoux\` (exact JSON).`,
    BLOCK_END,
  ];
  return lines.join("\n");
}

/** Replace the managed block in `existing` (or append it), leaving every other line untouched. */
export function upsertBlock(existing: string | null, block: string): string {
  if (!existing) return `${block}\n`;
  const start = existing.indexOf(BLOCK_BEGIN);
  const end = existing.indexOf(BLOCK_END);
  if (start >= 0 && end > start) return `${existing.slice(0, start)}${block}${existing.slice(end + BLOCK_END.length)}`;
  return `${existing.replace(/\s*$/, "")}\n\n${block}\n`;
}

/* ----------------------------------------------------------------- DESIGN.md */

function key(token: ResolvedToken): string {
  return token.id.split(".").slice(1).join("-");
}

function frontmatter(project: Project, build: TokenBuild): Record<string, unknown> {
  const byGroup = (group: string) => build.tokens.filter((t) => t.id.startsWith(`${group}.`));
  const colors: Record<string, string> = {};
  for (const t of byGroup("color")) {
    colors[key(t)] = cssValue(t.type, t.light);
    const dark = cssValue(t.type, t.dark);
    if (dark !== colors[key(t)]) colors[`${key(t)}-dark`] = dark;
  }
  const typography: Record<string, Record<string, string | number>> = {};
  for (const t of byGroup("typography")) {
    const v = t.light as { fontFamily: string[] | string; fontSize: { value: number; unit: string }; fontWeight: number; lineHeight: number; letterSpacing?: { value: number; unit: string } };
    typography[key(t)] = {
      fontFamily: cssValue("fontFamily", v.fontFamily),
      fontSize: `${v.fontSize.value}${v.fontSize.unit}`,
      fontWeight: v.fontWeight,
      lineHeight: v.lineHeight,
      ...(v.letterSpacing ? { letterSpacing: `${v.letterSpacing.value}${v.letterSpacing.unit}` } : {}),
    };
  }
  const dims = (group: string): Record<string, string> => Object.fromEntries(byGroup(group).map((t) => [key(t), cssValue(t.type, t.light)]));
  const ref = (tokenId: string): string | null => {
    const id = tokenId.replace(/^youi:[a-z-]+\/token\//, "");
    const [group, ...rest] = id.split(".");
    const name = rest.join("-");
    return group === "color" ? `{colors.${name}}` : group === "radius" ? `{rounded.${name}}` : group === "typography" ? `{typography.${name}}` : null;
  };
  const property: Record<string, string> = { bg: "backgroundColor", fg: "textColor", radius: "rounded", text: "typography", border: "borderColor" };
  const components: Record<string, Record<string, string>> = {};
  for (const { contract } of project.system.components) {
    const base = contract.name.toLowerCase();
    for (const [binding, tokenId] of Object.entries(contract.tokens)) {
      const [prop, variant] = binding.split(".");
      const field = property[prop ?? ""];
      const value = ref(tokenId);
      if (!field || !value) continue;
      const name = variant && variant !== "default" ? `${base}-${variant}` : base;
      components[name] = { ...components[name], [field]: value };
    }
  }
  return {
    name: project.system.config.name,
    description: project.system.config.description,
    colors,
    typography,
    rounded: dims("radius"),
    spacing: Object.fromEntries(Object.entries(dims("space"))),
    components,
  };
}

function componentsSection(project: Project): string {
  const rows = project.system.components.map(({ contract }) => `| ${contract.name} | \`${importLine(project, contract)}\` | ${enumSummary(contract) || "—"} | ${contract.summary} |`);
  return ["## Components (contracts)", "", "| Component | Import | Values | Use |", "| --- | --- | --- | --- |", ...rows].join("\n");
}

function rulesSection(project: Project): string {
  const rows = project.system.rules.map((r) => `| ${r.title} | ${r.severity} | ${r.check.engine === "advisory" ? "advisory (not checked)" : "checked by `youi check`"} | ${r.statement} |`);
  return ["## Rules", "", "| Rule | Severity | Enforcement | Statement |", "| --- | --- | --- | --- |", ...rows].join("\n");
}

export function designMd(project: Project, build: TokenBuild, narrative: string | null): string {
  const fm = stringify(frontmatter(project, build), { lineWidth: 0 }).trimEnd();
  const lookup = [
    "## Look it up",
    "",
    "- Exact contracts, tokens and rules: MCP server `youiyoux` (`youi_get_component`, `youi_get_tokens`, `youi_get_rules`) or `youi where <component>`.",
    "- Where something is used, screen by screen: `youi where <component> [--route <route>]` or `youi_where_used`.",
    "- Before finishing UI work: `youi check`.",
  ].join("\n");
  const body = (narrative ?? `# Design System: ${project.system.config.name}\n`).replace(/^<!--[\s\S]*?-->\s*/, "").trim();
  return `---\n${fm}\n---\n\n<!-- ${generatedNote(project)} -->\n\n${body}\n\n${componentsSection(project)}\n\n${rulesSection(project)}\n\n${lookup}\n`;
}

/* ------------------------------------------------------------------ SKILL.md */

export function skillMd(project: Project, uncontracted: readonly string[] = []): string {
  const { config, system } = project;
  const from = config.importFrom ?? config.componentsDir;
  const description = `Build and fix UI with the ${system.config.name} design language (YouIyouX): owned components, tokens, rules, where-used lookups and change proposals. Use for any UI, styling, colour or component work in this project.`;
  const components = system.components.map(({ contract }) => `- **${contract.name}**: ${contract.summary}${enumSummary(contract) ? ` (${enumSummary(contract)})` : ""}`);
  const fixes = enforced(system.rules).map((r) => `| \`${r.id.split("/rule/")[1]}\` | ${r.severity} | ${r.agent} |`);
  return [
    "---",
    "name: youiyoux",
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    `<!-- ${generatedNote(project)} -->`,
    "",
    `# ${system.config.name} design language`,
    "",
    "## Build a screen",
    "",
    "1. Find what exists: `youi_search` (MCP) or the component list below. Prefer an existing component over new markup.",
    "2. Read the contract before using props: `youi_get_component {\"name\": \"Button\"}`, or `youi show button` without MCP. Use only the listed values; `guidance` says when to use which.",
    `3. Import from \`${from}\`. Never import a component of the same name from anywhere else.`,
    "4. Colour, type, radius and shadow come from tokens: `youi_get_tokens {\"group\": \"color\"}` gives each token's CSS variable and a Tailwind utility (a colour works with bg-, text- and border-). Never write a hex, rgb() or a `[arbitrary]` value that copies a token.",
    "5. Run `youi check` and fix every error; warnings need a reason if left.",
    "",
    "## Fix a violation",
    "",
    "Each finding names its rule, the file:line and a suggestion. The suggested token is an exact value match: confirm the role before using it.",
    "",
    "| Rule | Severity | Do |",
    "| --- | --- | --- |",
    ...fixes,
    "",
    "## Find where something is used",
    "",
    "`youi where button` lists sites by screen, with prop usage and anything the scanner could not resolve (unknown is never counted as zero). Filter with `--route /settings`. MCP: `youi_where_used`, and `youi_screen_bom {\"route\": \"/settings\"}` for everything on one screen.",
    "",
    "## Propose a change to the system",
    "",
    "1. Plan it: `youi plan button --patch '{\"status\": \"deprecated\"}'` (or `youi_plan`). The plan computes the change class, semver bump, affected screens and which call sites a codemod can rewrite.",
    "2. Put the plan in your summary or PR description for a person to approve. Agents never approve, publish or merge design changes.",
    `3. Never hand-edit \`${GENERATED_MARK}\` files; they are rewritten on the next sync.`,
    "",
    "## Components",
    "",
    ...components,
    "",
    ...(uncontracted.length > 0
      ? [
          `Also in \`${config.componentsDir}\`, owned but without a contract yet (no checked props, not in the usage map): ${uncontracted.join(", ")}. Use them when they fit; ask for a contract before relying on their props.`,
          "",
        ]
      : []),
  ].join("\n");
}

/* --------------------------------------------------------- ast-grep rules */

/** Rules plain ast-grep can enforce without youi's import resolution, as ast-grep YAML. */
export function astGrepRules(project: Project): Array<{ file: string; content: string }> {
  const out: Array<{ file: string; content: string }> = [];
  const header = `# ${generatedNote(project)}\n# Portable subset: youi check also resolves imports; these run with plain \`ast-grep scan -r <file>\`.\n`;
  for (const rule of project.system.rules) {
    if (rule.check.engine === "ast-grep") {
      out.push({ file: `${rule.id.split("/rule/")[1]}.yml`, content: header + stringify({ id: rule.id, language: rule.check.language, severity: rule.severity === "error" ? "error" : "warning", message: rule.title, note: rule.agent, rule: rule.check.rule }) });
    }
    if (rule.check.engine === "youi" && rule.check.id === "native-element") {
      const tags = Object.keys((rule.check.options as { elements?: Record<string, string> }).elements ?? {});
      const regex = `^(${tags.join("|")})$`;
      out.push({
        file: `${rule.id.split("/rule/")[1]}.yml`,
        content: header + stringify({ id: rule.id, language: "tsx", severity: rule.severity === "error" ? "error" : "warning", message: rule.title, note: rule.agent, ignores: [`${project.config.componentsDir}/**`], rule: { any: [{ kind: "jsx_opening_element", has: { field: "name", regex } }, { kind: "jsx_self_closing_element", has: { field: "name", regex } }] } }),
      });
    }
    if (rule.check.engine === "youi" && rule.check.id === "raw-color") {
      out.push({
        file: `${rule.id.split("/rule/")[1]}.yml`,
        content: header + stringify({ id: rule.id, language: "tsx", severity: rule.severity === "error" ? "error" : "warning", message: rule.title, note: rule.agent, rule: { kind: "string_fragment", regex: "(\\[#[0-9a-fA-F]{3,8}\\]|^#[0-9a-fA-F]{3,8}$|rgba?\\()", inside: { kind: "jsx_attribute", stopBy: "end" } } }),
      });
    }
  }
  return out;
}
