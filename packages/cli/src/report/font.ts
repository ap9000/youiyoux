export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Letters drawn two rows down: their seven rows are x-height plus the tail. */
export const DESCENDERS: ReadonlySet<string> = new Set(["g", "p", "q", "y"]);

/** Rows of each glyph as bit masks, the leftmost column the highest bit. */
export const GLYPHS: ReadonlyMap<string, readonly number[]> = new Map(
  TABLE.slice(1, -1).split("\n").map((line) => [line[0]!, line.slice(2).split(" ").map((row) => Number.parseInt(row.replace(/\./g, "0").replace(/#/g, "1"), 2))] as const),
);

/** Text the font can draw: accents dropped, typographic marks made plain, anything else a "?". */
export function plainAscii(text: string): string {
  return text
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2013\u2014\u00b7]/g, "-")
    .replace(/\u2026/g, "...")
    .replace(/[^\x20-\x7e]/g, "?");
}
