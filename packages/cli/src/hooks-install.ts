/**
 * `youiyoux hooks install`: wire the checks into a product repo without disturbing what
 * is already there.
 *
 * - Claude Code: merges one PostToolUse entry into `.claude/settings.local.json`
 *   (local, because the command names this machine's youi checkout); every other
 *   setting and hook is kept, and reinstalling replaces only youi's own entry.
 * - git pre-commit: adds a marked block to the hook git actually runs (honouring
 *   core.hooksPath, so husky-style setups keep working); an existing shell hook keeps
 *   its content, a non-shell hook is left alone with instructions.
 * - CI: writes `.github/workflows/youi-check.yml`, pinned to this tool commit and the
 *   design repo commit (the rules version); an existing different file is not replaced
 *   without --force. With --diff (kept on reinstall), pull requests also run
 *   `youiyoux check --diff origin/<base> --strict --format github`.
 * - Codex: no documented post-edit hook to install, so nothing is written for it; Codex
 *   gets the findings from the pre-commit hook and from AGENTS.md (`youiyoux sync` writes the
 *   instruction to run `youiyoux check --diff` after UI edits).
 */
import { execFile } from "node:child_process";
import { chmod, mkdir, realpath } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { promisify } from "node:util";
import { readTextOrNull, toPosix, writeFileAtomic } from "@youiyoux/core";
import { PROJECT_FILE, type Project } from "@youiyoux/scanner";
import { repoAgentsBlock, RULE_BEGIN, RULE_END, upsertBlock } from "./agents.ts";
import { ephemeralTool, toolCommand } from "./tool-command.ts";
import type { HookTarget } from "./hooks.ts";

const run = promisify(execFile);
const CLAUDE_MARKER = "hooks run claude";
const BLOCK_START = "# >>> youi pre-commit >>>";
const BLOCK_END = "# <<< youi pre-commit <<<";
const WORKFLOW = ".github/workflows/youi-check.yml";
const WORKFLOW_HEADER = "# Generated by `youiyoux hooks install --ci`.";
const LEGACY_WORKFLOW_HEADER = WORKFLOW_HEADER.replace("youiyoux", "youi");
const managedWorkflow = (text: string): boolean => text.startsWith(WORKFLOW_HEADER) || text.startsWith(LEGACY_WORKFLOW_HEADER);
const DIFF_STEP = "name: youiyoux check --diff";
const CLAUDE_MATCHER = "Edit|Write|MultiEdit";
const CLAUDE_TIMEOUT_S = 60;

/** POSIX single-quoting: safe for spaces, quotes and $ in paths. */
export const shellQuote = (arg: string): string => (/^[\w@%+=:,./-]+$/.test(arg) ? arg : `'${arg.replace(/'/g, `'\\''`)}'`);

interface InstallResult {
  readonly file: string;
  /** skipped: nothing to install (Codex), with what covers it instead. */
  readonly action: "created" | "updated" | "unchanged" | "skipped";
  /** What this hook does and does not guarantee. */
  readonly guarantee: string;
}

async function gitOut(cwd: string, args: readonly string[]): Promise<string> {
  return (await run("git", [...args], { cwd })).stdout.trim();
}

export async function repoRootOf(dir: string): Promise<string> {
  return gitOut(dir, ["rev-parse", "--show-toplevel"]).catch(() => dir);
}

/** The command a hook runs: this youi, pointed at this project (and its out-of-repo config, if any). */
export function hookCommand(toolRoot: string, kind: "claude" | "pre-commit", target: HookTarget, extra: readonly string[] = []): string {
  const server = toolCommand(toolRoot);
  const args = [server.command, ...server.args, "hooks", "run", kind];
  for (const key of ["project", "config", "design", "root"] as const) {
    const value = target[key];
    if (value) args.push(`--${key}`, resolve(value));
  }
  return [...args, ...extra].map(shellQuote).join(" ");
}

/** Write `content` unless it is already there; created, updated or unchanged. */
export async function write(file: string, content: string, before: string | null, guarantee: string, mode?: number): Promise<InstallResult> {
  if (before === content) return { file, action: "unchanged", guarantee };
  await mkdir(dirname(file), { recursive: true });
  await writeFileAtomic(file, content);
  if (mode !== undefined) await chmod(file, mode);
  return { file, action: before === null ? "created" : "updated", guarantee };
}

/* ----------------------------------------------------------------- Claude Code */

interface HookEntry {
  readonly matcher?: string;
  readonly hooks?: ReadonlyArray<{ readonly type?: string; readonly command?: string; readonly timeout?: number }>;
}

const isYouiEntry = (entry: HookEntry): boolean => (entry.hooks ?? []).some((h) => typeof h.command === "string" && h.command.includes(CLAUDE_MARKER));

export async function installClaudeHook(repoRoot: string, command: string): Promise<InstallResult> {
  const file = join(repoRoot, ".claude/settings.local.json");
  const before = await readTextOrNull(file);
  let settings: Record<string, unknown>;
  try {
    settings = before === null ? {} : (JSON.parse(before) as Record<string, unknown>);
  } catch {
    throw new Error(`${file} is not valid JSON; fix it first (youi will not overwrite it)`);
  }
  const hooks = (settings.hooks ?? {}) as Record<string, readonly HookEntry[]>;
  const existing = hooks.PostToolUse ?? [];
  const entry: HookEntry = { matcher: CLAUDE_MATCHER, hooks: [{ type: "command", command, timeout: CLAUDE_TIMEOUT_S }] };
  const postToolUse = existing.some(isYouiEntry) ? existing.map((e) => (isYouiEntry(e) ? entry : e)) : [...existing, entry];
  const next = { ...settings, hooks: { ...hooks, PostToolUse: postToolUse } };
  return write(file, `${JSON.stringify(next, null, 2)}\n`, before, "advisory: after each Claude Code Edit/Write/MultiEdit, that file's new violations go back to Claude; never blocks; edits made any other way are not seen");
}

/* -------------------------------------------------------------- git pre-commit */

function withBlock(script: string | null, block: string): string {
  if (script === null) return `#!/bin/sh\n${block}\n`;
  const start = script.indexOf(BLOCK_START);
  const end = script.indexOf(BLOCK_END);
  if (start >= 0 && end > start) return `${script.slice(0, start)}${block}${script.slice(end + BLOCK_END.length)}`;
  return `${script.endsWith("\n") ? script : `${script}\n`}\n${block}\n`;
}

export async function installPreCommit(projectRoot: string, command: string, strict: boolean): Promise<InstallResult> {
  const hooksDir = resolve(projectRoot, await gitOut(projectRoot, ["rev-parse", "--git-path", "hooks"]));
  const file = join(hooksDir, "pre-commit");
  const before = await readTextOrNull(file);
  const shebang = before?.split("\n", 1)[0] ?? "";
  if (before !== null && shebang.startsWith("#!") && !/\b(?:sh|bash|zsh|dash)\b/.test(shebang)) {
    throw new Error(`${file} is not a shell script (${shebang}); add this line to it yourself: ${command}`);
  }
  if (before !== null && /^\s*exec\s/m.test(before) && !before.includes(BLOCK_START)) {
    throw new Error(`${file} hands off with exec, so an appended check would never run; add this line before the exec yourself: ${command}`);
  }
  const what = strict ? "Blocks commits with new design-system errors" : "Advisory, never blocks";
  const block = `${BLOCK_START}\n# ${what}: checks the staged content of staged files only; CI is authoritative.\n${command} || exit $?\n${BLOCK_END}`;
  const guarantee = strict
    ? "blocks commits with new errors in staged files (any agent or person that commits; --no-verify skips it)"
    : "advisory at commit time, staged files only (any agent or person that commits; not every edit)";
  return write(file, withBlock(before, block), before, guarantee, 0o755);
}

/* -------------------------------------------------------------------- Codex */

/** Give repo-mode agents the same post-edit instruction sync writes for configured projects, using a portable command for teammates too. */
export async function installRepoAgentInstructions(root: string): Promise<InstallResult> {
  const file = join(root, "AGENTS.md");
  const before = await readTextOrNull(file);
  const guarantee = "agents run youiyoux check --diff after UI edits; pre-commit also checks staged edits";
  // `youiyoux agents install`'s block already says it: one check --diff line per file.
  const ruled = before !== null && before.indexOf(RULE_END) > before.indexOf(RULE_BEGIN) && before.includes(RULE_BEGIN);
  return write(file, ruled ? before : upsertBlock(before, repoAgentsBlock(root)), before, guarantee);
}

/** Codex has no documented hook that runs after its edits: say what covers it instead, and install nothing. */
export function codexFallback(projectRoot: string, agentsFile: string): InstallResult {
  return {
    file: join(projectRoot, agentsFile),
    action: "skipped",
    guarantee: "no post-edit hook installed (Codex documents none): Codex follows AGENTS.md, where `youiyoux sync` tells it to run `youiyoux check --diff` after UI edits, and the git pre-commit hook checks what it commits",
  };
}

/* ----------------------------------------------------------------------- CI */

/** owner/name from a GitHub remote URL, or null. */
export function githubSlug(url: string): string | null {
  const match = /github\.com[:/]([^/\s]+)\/([^/\s]+?)(?:\.git)?\/?$/.exec(url.trim());
  return match ? `${match[1]}/${match[2]}` : null;
}

async function repoAt(root: string): Promise<{ slug: string; commit: string }> {
  const slug = githubSlug(await gitOut(root, ["remote", "get-url", "origin"]).catch(() => ""));
  if (!slug) throw new Error(`${root} has no GitHub origin remote; the workflow needs one to check it out`);
  return { slug, commit: await gitOut(root, ["rev-parse", "HEAD"]) };
}

const posix = (path: string): string => toPosix(path) || ".";
const inside = (root: string, path: string): boolean => !relative(root, path).startsWith("..");

interface WorkflowInput {
  readonly tool: { readonly slug: string; readonly commit: string };
  readonly design: { readonly slug: string; readonly commit: string };
  /** The project's directory inside its repository ("." at the root). */
  readonly projectDir: string;
  /** The project config, when it is not `<projectDir>/youi.project.json`. */
  readonly configPath: string | null;
  /** Also run `youiyoux check --diff` on pull requests: fail on drift the PR adds. */
  readonly diff?: boolean;
}

export function workflowText(input: WorkflowInput): string {
  // A config from elsewhere may name its product with "root"; in CI the product is this checkout, so --root says so.
  // Never an empty argument: `--root ''` would read as unset, and the config's own root would win.
  const dir = input.projectDir || ".";
  const target = ["--project", dir, "--design", ".youi-ci/design", ...(input.configPath ? ["--config", input.configPath, "--root", dir] : [])];
  const checkArgs = ["--baseline", "--format", "github", ...target].map(shellQuote).join(" ");
  const diffArgs = ["--strict", "--format", "github", ...target].map(shellQuote).join(" ");
  // The base branch name comes from the event: passed through the environment, never pasted into the script.
  const diffStep = input.diff
    ? `      - ${DIFF_STEP} (drift this pull request adds)
        if: \${{ !cancelled() && github.event_name == 'pull_request' }}
        env:
          YOUI_BASE: \${{ github.base_ref }}
        run: node .youi-ci/tool/packages/cli/bin/youi.js check --diff "origin/$YOUI_BASE" ${diffArgs}
`
    : "";
  return `${WORKFLOW_HEADER}
# The authoritative design-system check: it fails on violations the baseline does not
# accept, annotates them on the PR's lines, and states the rules version (design commit
# and definitions digest) in the job summary. Raise the rules version by changing the
# design ref below; YOUI_REPO_TOKEN must be able to read both repositories.
name: youiyoux check
on:
  pull_request:
  push:
    branches: [main]
permissions:
  contents: read
jobs:
  youi-check:
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@v4${input.diff ? "\n        with:\n          fetch-depth: 0" : ""}
      - name: Check out youi
        uses: actions/checkout@v4
        with:
          repository: ${input.tool.slug}
          ref: ${input.tool.commit}
          path: .youi-ci/tool
          token: \${{ secrets.YOUI_REPO_TOKEN }}
      - name: Check out the design rules (the rules version)
        uses: actions/checkout@v4
        with:
          repository: ${input.design.slug}
          ref: ${input.design.commit}
          path: .youi-ci/design
          token: \${{ secrets.YOUI_REPO_TOKEN }}
      - uses: pnpm/action-setup@v4
        with:
          version: 10.13.1
      - uses: actions/setup-node@v4
        with:
          node-version: 24
      - run: pnpm install --frozen-lockfile --ignore-scripts
        working-directory: .youi-ci/tool
      - name: youiyoux check
        run: node .youi-ci/tool/packages/cli/bin/youi.js check ${checkArgs}
${diffStep}`;
}

export async function installWorkflow(project: Project, toolRoot: string, target: HookTarget, force: boolean, options: { diff?: boolean } = {}): Promise<InstallResult> {
  const top = await gitOut(project.root, ["rev-parse", "--show-toplevel"]);
  // From a package-runner cache (npx), CI runs the published package instead of checking this tool out.
  const published = ephemeralTool(toolRoot);
  const [tool, design] = await Promise.all([published ? Promise.resolve({ slug: "npm/youiyoux", commit: "published" }) : repoAt(toolRoot), repoAt(project.repo.root)]);
  const configFile = resolve(target.config ?? project.configFile ?? join(project.root, PROJECT_FILE));
  const configPath = !target.config ? null : inside(project.repo.root, configFile) ? `.youi-ci/design/${posix(relative(project.repo.root, configFile))}` : inside(top, configFile) ? posix(relative(top, configFile)) : null;
  if (target.config && !configPath) throw new Error(`${configFile} is in neither this repo nor the design repo, so CI cannot read it`);
  const file = join(top, WORKFLOW);
  const before = await readTextOrNull(file);
  if (before !== null && !managedWorkflow(before) && !force) throw new Error(`${file} exists and was not written by youi; pass --force to replace it`);
  // A diff step installed before is kept: reinstalling without --diff does not drop it.
  const diff = options.diff === true || (before !== null && managedWorkflow(before) && (before.includes(DIFF_STEP) || before.includes(DIFF_STEP.replace("youiyoux", "youi"))));
  // git reports the top level with symlinks resolved (/private/var for /var): compare real paths.
  const projectDir = posix(relative(top, await realpath(project.root).catch(() => project.root)));
  let text = workflowText({ tool, design, projectDir, configPath, diff });
  if (published) {
    text = text.replace(/      - name: Check out youi\n[\s\S]*?(?=      - name: Check out the design)/, "").replace(/      - run: pnpm install --frozen-lockfile --ignore-scripts\n        working-directory: .youi-ci\/tool\n/, "").replaceAll("node .youi-ci/tool/packages/cli/bin/youi.js", "npx -y youiyoux");
  }
  return write(file, text, before, `authoritative: ${published ? "runs the published youiyoux package; pinned to" : `pinned to ${tool.slug}@${tool.commit.slice(0, 7)} and`} rules ${design.slug}@${design.commit.slice(0, 7)}${diff ? "; pull requests also fail on drift they add (youiyoux check --diff --strict)" : ""}`);
}

/* ------------------------------------------------------------------- record */

const RECORD_WORKFLOW = ".github/workflows/youiyoux-record.yml";
const RECORD_HEADER = "# Generated by `youiyoux hooks install --record`.";

/** How CI installs the repository's dependencies, from its lockfile (a package source is found in node_modules); null: none to install. */
export async function installStep(top: string): Promise<string | null> {
  const has = async (file: string): Promise<boolean> => (await readTextOrNull(join(top, file))) !== null;
  // corepack (in Node 24) rather than a third-party action: the step after this one holds the hub's token.
  if (await has("pnpm-lock.yaml")) return "      - run: corepack enable && pnpm install --frozen-lockfile --ignore-scripts\n";
  if (await has("yarn.lock")) return "      - run: corepack enable && yarn install --immutable --mode=skip-build\n";
  if (await has("package-lock.json")) return "      - run: npm ci --ignore-scripts\n";
  return null;
}

export function recordWorkflowText(input: { readonly branch: string; readonly version: string; readonly install: string | null }): string {
  const tool = `youiyoux@${input.version}`;
  return `${RECORD_HEADER}
# Sends where each product here stands with its System to your team's hosted hub
# (youiyoux hub serve): youiyoux record, redacted as the shareable report is, with no code.
# Set two repository secrets: YOUIYOUX_HUB_URL (the hub's https address) and
# YOUIYOUX_HUB_TOKEN (the hub's ingest token). Pinned to youiyoux ${input.version}; change it here.
# Only GitHub's own actions run here: the record step holds the token.
name: youiyoux record
on:
  push:
    branches: [${JSON.stringify(input.branch)}]
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: youiyoux-record
  cancel-in-progress: true
jobs:
  record:
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 24
${input.install ?? ""}      - name: youiyoux record
        env:
          YOUIYOUX_HUB_URL: \${{ secrets.YOUIYOUX_HUB_URL }}
          YOUIYOUX_HUB_TOKEN: \${{ secrets.YOUIYOUX_HUB_TOKEN }}
        run: npx -y ${tool} record --send
`;
}

/** The workflow that records this repository on each push to its default branch. */
export async function installRecordWorkflow(dir: string, version: string | null, force: boolean): Promise<InstallResult> {
  // Never an unpinned package in a step that holds a secret.
  if (!version) throw new Error("cannot tell which youiyoux version this is, so the workflow could not be pinned: run npx youiyoux@<version> hooks install --record");
  const top = await gitOut(dir, ["rev-parse", "--show-toplevel"]).catch(() => {
    throw new Error(`${dir} is not in a git repository; the record workflow runs in one`);
  });
  const remoteHead = await gitOut(top, ["symbolic-ref", "--short", "refs/remotes/origin/HEAD"]).catch(() => "");
  const branch = remoteHead.replace(/^origin\//, "") || (await gitOut(top, ["symbolic-ref", "--short", "HEAD"]).catch(() => "")) || "main";
  const file = join(top, RECORD_WORKFLOW);
  const before = await readTextOrNull(file);
  if (before !== null && !before.startsWith(RECORD_HEADER) && !force) throw new Error(`${file} exists and was not written by youiyoux; pass --force to replace it`);
  return write(file, recordWorkflowText({ branch, version, install: await installStep(top) }), before, `sends this repository's record (redacted, no code) to the hub in YOUIYOUX_HUB_URL on each push to ${branch}; set YOUIYOUX_HUB_URL and YOUIYOUX_HUB_TOKEN as repository secrets`);
}
