/** owner/name from a GitHub remote URL, or null. */
export function githubSlug(url: string): string | null {
  const match = /github\.com[:/]([^/\s]+)\/([^/\s]+?)(?:\.git)?\/?$/.exec(url.trim());
  return match ? `${match[1]}/${match[2]}` : null;
}

async function repoAt(root: string): Promise<{ slug: string; commit: string }> {
  const slug = githubSlug(await gitOut(root, ["remote", "get-url", "origin"]).catch(() => ""));
  if (!slug) throw new Error(`${root} has no GitHub origin remote; the workflow needs one to check it out`);
  return { slug, commit: await gitOut(root, ["rev-parse", "HEAD"]) };
}

const posix = (path: string): string => path.split(sep).join("/") || ".";
const inside = (root: string, path: string): boolean => !relative(root, path).startsWith("..");

export interface WorkflowInput {
  readonly tool: { readonly slug: string; readonly commit: string };
  readonly design: { readonly slug: string; readonly commit: string };
  /** The project's directory inside its repository ("." at the root). */
  readonly projectDir: string;
  /** The project config, when it is not `<projectDir>/youi.project.json`. */
  readonly configPath: string | null;
  /** Also run `youi check --diff` on pull requests: fail on drift the PR adds. */
  readonly diff?: boolean;
}

export function workflowText(input: WorkflowInput): string {
  // A config from elsewhere may name its product with "root"; in CI the product is this checkout, so --root says so.
  // Never an empty argument: `--root ''` would read as unset, and the config's own root would win.
  const dir = input.projectDir || ".";
  const target = ["--project", dir, "--design", ".youi-ci/design", ...(input.configPath ? ["--config", input.configPath, "--root", dir] : [])];
  const checkArgs = ["--baseline", "--format", "github", ...target].map(shellQuote).join(" ");
  const diffArgs = ["--strict", "--format", "github", ...target].map(shellQuote).join(" ");
  // The base branch name comes from the event: passed through the environment, never pasted into the script.
  const diffStep = input.diff
    ? `      - ${DIFF_STEP} (drift this pull request adds)
        if: \${{ !cancelled() && github.event_name == 'pull_request' }}
        env:
          YOUI_BASE: \${{ github.base_ref }}
        run: node .youi-ci/tool/packages/cli/bin/youi.js check --diff "origin/$YOUI_BASE" ${diffArgs}
`
    : "";
  return `${WORKFLOW_HEADER}
# The authoritative design-system check: it fails on violations the baseline does not
# accept, annotates them on the PR's lines, and states the rules version (design commit
# and definitions digest) in the job summary. Raise the rules version by changing the
# design ref below; YOUI_REPO_TOKEN must be able to read both repositories.
name: youi check
on:
  pull_request:
  push:
    branches: [main]
permissions:
  contents: read
jobs:
  youi-check:
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@v4${input.diff ? "\n        with:\n          fetch-depth: 0" : ""}
      - name: Check out youi
        uses: actions/checkout@v4
        with:
          repository: ${input.tool.slug}
          ref: ${input.tool.commit}
          path: .youi-ci/tool
          token: \${{ secrets.YOUI_REPO_TOKEN }}
      - name: Check out the design rules (the rules version)
        uses: actions/checkout@v4
        with:
          repository: ${input.design.slug}
          ref: ${input.design.commit}
          path: .youi-ci/design
          token: \${{ secrets.YOUI_REPO_TOKEN }}
      - uses: pnpm/action-setup@v4
        with:
          version: 10.13.1
      - uses: actions/setup-node@v4
        with:
          node-version: 24
      - run: pnpm install --frozen-lockfile --ignore-scripts
        working-directory: .youi-ci/tool
      - name: youi check
        run: node .youi-ci/tool/packages/cli/bin/youi.js check ${checkArgs}
${diffStep}`;
}

export async function installWorkflow(project: Project, toolRoot: string, target: HookTarget, force: boolean, options: { diff?: boolean } = {}): Promise<InstallResult> {
  const top = await gitOut(project.root, ["rev-parse", "--show-toplevel"]);
  const [tool, design] = await Promise.all([repoAt(toolRoot), repoAt(project.repo.root)]);
  const configFile = resolve(target.config ?? project.configFile ?? join(project.root, PROJECT_FILE));
  const configPath = !target.config ? null : inside(project.repo.root, configFile) ? `.youi-ci/design/${posix(relative(project.repo.root, configFile))}` : inside(top, configFile) ? posix(relative(top, configFile)) : null;
  if (target.config && !configPath) throw new Error(`${configFile} is in neither this repo nor the design repo, so CI cannot read it`);
  const file = join(top, WORKFLOW);
  const before = await readTextOrNull(file);
  if (before !== null && !before.startsWith(WORKFLOW_HEADER) && !force) throw new Error(`${file} exists and was not written by youi; pass --force to replace it`);
  // A diff step installed before is kept: reinstalling without --diff does not drop it.
  const diff = options.diff === true || (before?.startsWith(WORKFLOW_HEADER) === true && before.includes(DIFF_STEP));
  // git reports the top level with symlinks resolved (/private/var for /var): compare real paths.
  const projectDir = posix(relative(top, await realpath(project.root).catch(() => project.root)));
  const text = workflowText({ tool, design, projectDir, configPath, diff });
  return write(file, text, before, `authoritative: pinned to ${tool.slug}@${tool.commit.slice(0, 7)} and rules ${design.slug}@${design.commit.slice(0, 7)}${diff ? "; pull requests also fail on drift they add (youi check --diff --strict)" : ""}`);
}
