/**
 * `youi hooks install`: wire the checks into a product repo without disturbing what
 * is already there.
 *
 * - Claude Code: merges one PostToolUse entry into `.claude/settings.local.json`
 *   (local, because the command names this machine's youi checkout); every other
 *   setting and hook is kept, and reinstalling replaces only youi's own entry.
 * - git pre-commit: adds a marked block to the hook git actually runs (honouring
 *   core.hooksPath, so husky-style setups keep working); an existing shell hook keeps
 *   its content, a non-shell hook is left alone with instructions.
 * - CI: writes `.github/workflows/youi-check.yml`, pinned to this tool commit and the
 *   design repo commit (the rules version); an existing different file is not replaced
 *   without --force. With --diff (kept on reinstall), pull requests also run
 *   `youi check --diff origin/<base> --strict --format github`.
 * - Codex: no documented post-edit hook to install, so nothing is written for it; Codex
 *   gets the findings from the pre-commit hook and from AGENTS.md (`youi sync` writes the
 *   instruction to run `youi check --diff` after UI edits).
 */
import { execFile } from "node:child_process";
import { chmod, mkdir, realpath } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { promisify } from "node:util";
import { readTextOrNull, writeFileAtomic } from "@youiyoux/core";
import { PROJECT_FILE, type Project } from "@youiyoux/scanner";
import { repoAgentsBlock, upsertBlock } from "./agents.ts";
import type { HookTarget } from "./hooks.ts";

const run = promisify(execFile);
const CLAUDE_MARKER = "hooks run claude";
const BLOCK_START = "# >>> youi pre-commit >>>";
const BLOCK_END = "# <<< youi pre-commit <<<";
const WORKFLOW = ".github/workflows/youi-check.yml";
const WORKFLOW_HEADER = "# Generated by `youi hooks install --ci`.";
const DIFF_STEP = "name: youi check --diff";
const CLAUDE_MATCHER = "Edit|Write|MultiEdit";
const CLAUDE_TIMEOUT_S = 60;

/** POSIX single-quoting: safe for spaces, quotes and $ in paths. */
export const shellQuote = (arg: string): string => (/^[\w@%+=:,./-]+$/.test(arg) ? arg : `'${arg.replace(/'/g, `'\\''`)}'`);

export interface InstallResult {
  readonly file: string;
  /** skipped: nothing to install (Codex), with what covers it instead. */
  readonly action: "created" | "updated" | "unchanged" | "skipped";
  /** What this hook does and does not guarantee. */
  readonly guarantee: string;
}

async function gitOut(cwd: string, args: readonly string[]): Promise<string> {
  return (await run("git", [...args], { cwd })).stdout.trim();
}

export async function repoRootOf(dir: string): Promise<string> {
  return gitOut(dir, ["rev-parse", "--show-toplevel"]).catch(() => dir);
}

/** The command a hook runs: this youi, pointed at this project (and its out-of-repo config, if any). */
export function hookCommand(toolRoot: string, kind: "claude" | "pre-commit", target: HookTarget, extra: readonly string[] = []): string {
  const args = ["node", join(toolRoot, "packages/cli/bin/youi.js"), "hooks", "run", kind];
  for (const key of ["project", "config", "design", "root"] as const) {
    const value = target[key];
    if (value) args.push(`--${key}`, resolve(value));
  }
  return [...args, ...extra].map(shellQuote).join(" ");
}

/** Write `content` unless it is already there; created, updated or unchanged. */
export async function write(file: string, content: string, before: string | null, guarantee: string, mode?: number): Promise<InstallResult> {
  if (before === content) return { file, action: "unchanged", guarantee };
  await mkdir(dirname(file), { recursive: true });
  await writeFileAtomic(file, content);
  if (mode !== undefined) await chmod(file, mode);
  return { file, action: before === null ? "created" : "updated", guarantee };
}

/* ----------------------------------------------------------------- Claude Code */

interface HookEntry {
  readonly matcher?: string;
  readonly hooks?: ReadonlyArray<{ readonly type?: string; readonly command?: string; readonly timeout?: number }>;
}

const isYouiEntry = (entry: HookEntry): boolean => (entry.hooks ?? []).some((h) => typeof h.command === "string" && h.command.includes(CLAUDE_MARKER));

export async function installClaudeHook(repoRoot: string, command: string): Promise<InstallResult> {
  const file = join(repoRoot, ".claude/settings.local.json");
  const before = await readTextOrNull(file);
  let settings: Record<string, unknown>;
  try {
    settings = before === null ? {} : (JSON.parse(before) as Record<string, unknown>);
  } catch {
    throw new Error(`${file} is not valid JSON; fix it first (youi will not overwrite it)`);
  }
  const hooks = (settings.hooks ?? {}) as Record<string, readonly HookEntry[]>;
  const existing = hooks.PostToolUse ?? [];
  const entry: HookEntry = { matcher: CLAUDE_MATCHER, hooks: [{ type: "command", command, timeout: CLAUDE_TIMEOUT_S }] };
  const postToolUse = existing.some(isYouiEntry) ? existing.map((e) => (isYouiEntry(e) ? entry : e)) : [...existing, entry];
  const next = { ...settings, hooks: { ...hooks, PostToolUse: postToolUse } };
  return write(file, `${JSON.stringify(next, null, 2)}\n`, before, "advisory: after each Claude Code Edit/Write/MultiEdit, that file's new violations go back to Claude; never blocks; edits made any other way are not seen");
}

/* -------------------------------------------------------------- git pre-commit */

function withBlock(script: string | null, block: string): string {
  if (script === null) return `#!/bin/sh\n${block}\n`;
  const start = script.indexOf(BLOCK_START);
  const end = script.indexOf(BLOCK_END);
  if (start >= 0 && end > start) return `${script.slice(0, start)}${block}${script.slice(end + BLOCK_END.length)}`;
  return `${script.endsWith("\n") ? script : `${script}\n`}\n${block}\n`;
}

export async function installPreCommit(projectRoot: string, command: string, strict: boolean): Promise<InstallResult> {
  const hooksDir = resolve(projectRoot, await gitOut(projectRoot, ["rev-parse", "--git-path", "hooks"]));
  const file = join(hooksDir, "pre-commit");
  const before = await readTextOrNull(file);
  const shebang = before?.split("\n", 1)[0] ?? "";
  if (before !== null && shebang.startsWith("#!") && !/\b(?:sh|bash|zsh|dash)\b/.test(shebang)) {
    throw new Error(`${file} is not a shell script (${shebang}); add this line to it yourself: ${command}`);
  }
  if (before !== null && /^\s*exec\s/m.test(before) && !before.includes(BLOCK_START)) {
    throw new Error(`${file} hands off with exec, so an appended check would never run; add this line before the exec yourself: ${command}`);
  }
  const what = strict ? "Blocks commits with new design-system errors" : "Advisory, never blocks";
  const block = `${BLOCK_START}\n# ${what}: checks the staged content of staged files only; CI is authoritative.\n${command} || exit $?\n${BLOCK_END}`;
  const guarantee = strict
    ? "blocks commits with new errors in staged files (any agent or person that commits; --no-verify skips it)"
    : "advisory at commit time, staged files only (any agent or person that commits; not every edit)";
  return write(file, withBlock(before, block), before, guarantee, 0o755);
}

/* -------------------------------------------------------------------- Codex */

/** Give repo-mode agents the same post-edit instruction sync writes for configured projects, invoking youi the way the hooks do (it is often not on PATH). */
export async function installRepoAgentInstructions(root: string, toolRoot: string): Promise<InstallResult> {
  const file = join(root, "AGENTS.md");
  const before = await readTextOrNull(file);
  const run = ["node", join(toolRoot, "packages/cli/bin/youi.js")].map(shellQuote).join(" ");
  return write(file, upsertBlock(before, repoAgentsBlock(run)), before, "agents run youi check --diff after UI edits; pre-commit also checks staged edits");
}

/** Codex has no documented hook that runs after its edits: say what covers it instead, and install nothing. */
export function codexFallback(projectRoot: string, agentsFile: string): InstallResult {
  return {
    file: join(projectRoot, agentsFile),
    action: "skipped",
    guarantee: "no post-edit hook installed (Codex documents none): Codex follows AGENTS.md, where `youi sync` tells it to run `youi check --diff` after UI edits, and the git pre-commit hook checks what it commits",
  };
}

