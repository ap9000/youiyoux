/**
 * Token build: Terrazzo parses and resolves the DTCG 2025.10 resolver document
 * (sets + a light/dark modifier) and emits the CSS custom properties; the other
 * targets (Tailwind v4 @theme, TS, React Native) are rendered from the same
 * resolved values in outputs.ts.
 */
import { readFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { aliasesIn, CSS_SAFE_NAME, DefinitionError, toPosix, validateTokenSets, type ComponentContract, type OutputConfig, type SystemConfig } from "@youiyoux/core";
import { build, defineConfig, parse, type TokenNormalized } from "@terrazzo/parser";
import cssPlugin from "@terrazzo/plugin-css";
import { DL_EXT } from "./import.ts";
import { resolverLayout } from "./layout.ts";
import { renderNative, renderTailwind, renderTs, stateVariables, youiTypeVariables } from "./outputs.ts";
import { cssComment, cssString, cssValue, resolveAliases } from "./values.ts";

export interface ResolvedToken {
  readonly id: string;
  readonly type: string;
  readonly light: unknown;
  readonly dark: unknown;
  /** Token id this one aliases (in the light scheme), if any. */
  readonly aliasOf?: string;
  /** Token id this one aliases in the dark scheme, when that differs from the light one. */
  readonly darkAliasOf?: string;
  /** The `$value` as written per scheme, aliases kept (`{color.brand}`), so an editor can change it without flattening aliases. */
  readonly source?: { readonly light: unknown; readonly dark: unknown };
  /** Every token this one's value reads, in either scheme: whole aliases and parts (a typography's fontFamily). */
  readonly dependsOn?: readonly string[];
  /** CSS variable name without `--` and prefix. */
  readonly cssName: string;
  readonly description?: string;
}

export interface OutputFile {
  /** Path relative to the project's outputs.dir. */
  readonly path: string;
  readonly content: string;
}

export interface TokenBuild {
  readonly system: string;
  readonly version: string;
  readonly prefix: string;
  readonly tokens: readonly ResolvedToken[];
  readonly files: readonly OutputFile[];
}

const QUIET_LOGGER_LEVEL = "error";

export function cssNameOf(token: Pick<TokenNormalized, "id" | "$extensions">): string {
  const ext = token.$extensions?.[DL_EXT] as { css?: string } | undefined;
  return ext?.css ?? token.id.replace(/\./g, "-");
}

export function generatedHeader(system: SystemConfig, commentStyle: "css" | "ts"): string {
  // The system's name is free text: keep it on one line and unable to close the comment.
  const line = `@generated by youi from the ${cssComment(system.name)} design language v${system.version}. Do not edit: change the tokens in the design repo and run \`youi sync\`.`;
  return commentStyle === "css" ? `/* ${line} */` : `// ${line}`;
}

function themeInputs(system: SystemConfig): { light: Record<string, string>; dark: Record<string, string> } {
  const modifier = system.themeModifier;
  if (!modifier) return { light: {}, dark: {} };
  return { light: { [modifier.name]: modifier.light }, dark: { [modifier.name]: modifier.dark } };
}

/** Terrazzo leaves the first declaration unindented; normalize every line to two spaces. */
function indent(contents: string, keepComments = true): string {
  return contents
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && (keepComments || !line.startsWith("/*")))
    .map((line) => `  ${line}`)
    .join("\n");
}

function wrapDark(contents: string, output: OutputConfig): string {
  const body = `  color-scheme: dark;\n${indent(contents, false)}`;
  return output.dark
    .map(({ media, selector }) => (media ? `@media ${media} {\n  ${selector} {\n${body.replace(/^/gm, "  ")}\n  }\n}` : `${selector} {\n${body}\n}`))
    .join("\n\n");
}

/** Terrazzo dependency pointers (`#/font/sans/$value`) → token ids (`font.sans`). */
function dependencyIds(...tokens: Array<TokenNormalized | undefined>): string[] {
  const ids = tokens.flatMap((token) => [...(token?.dependencies ?? []), ...(token?.aliasOf ? [`#/${token.aliasOf.replace(/\./g, "/")}/$value`] : [])]);
  return [...new Set(ids.map((pointer) => pointer.replace(/^#\//, "").split("/$value")[0]!.replace(/\//g, ".")))].sort();
}

function differs(light: TokenNormalized, dark: TokenNormalized | undefined): boolean {
  return dark !== undefined && JSON.stringify(light.$value) !== JSON.stringify(dark.$value) && !light.aliasOf;
}

/** Every CSS variable name the build would write must be an identifier: a name or a `css` override with punctuation could add a declaration. */
function unsafeNames(tokens: Record<string, TokenNormalized>, file: string): void {
  const problems = Object.values(tokens)
    .filter((token) => !CSS_SAFE_NAME.test(cssNameOf(token)))
    .map((token) => `${token.id}: its CSS variable name "${cssNameOf(token)}" may hold only letters, digits, hyphens and underscores`);
  if (problems.length > 0) throw new DefinitionError(file, problems);
}

/** A family name as Terrazzo writes it (`"${name}"` unless a keyword), with what could close the quotes escaped. */
const terrazzoFamily = (name: string): string => (/^[a-z-]+$/.test(name) ? name : cssString(name));
/** The same, inside the quotes Terrazzo adds itself (its typography transform quotes each family). */
const escapedInside = (name: string): string => (/^[a-z-]+$/.test(name) ? name : cssString(name).slice(1, -1));
const familyList = (value: unknown): string[] => (Array.isArray(value) ? value.map(String) : [String(value)]);

/** The youi types Terrazzo parses but does not emit or resolve inside: the build lowers them itself. */
const YOUI_TYPES = new Set(["spring", "focusRing"]);

export interface BuildOptions {
  /** Contracts whose `states` become component state variables (`--<prefix>-<component>-<state>-<role>`). */
  readonly contracts?: readonly Pick<ComponentContract, "id" | "states">[];
}

/**
 * Check every token file the resolver reads with youi.tokens/v1 (each value against its type,
 * aliases resolve, no cycles) before Terrazzo sees it, so a malformed spring or focus ring stops
 * the build with its file and token path instead of being dropped from the output.
 */
async function validateSets(repoRoot: string, system: SystemConfig, resolverText: string): Promise<void> {
  const resolverFile = join(repoRoot, system.tokens);
  const where = (file: string): string => toPosix(relative(repoRoot, file));
  let document: unknown;
  try {
    document = JSON.parse(resolverText);
  } catch (error: unknown) {
    throw new DefinitionError(where(resolverFile), [`not valid JSON: ${error instanceof Error ? error.message : String(error)}`]);
  }
  const files = resolverLayout(document, system.themeModifier).files.map((ref) => join(dirname(resolverFile), ref));
  const sources = await Promise.all(
    files.map(async (file) => {
      try {
        return { file: where(file), document: JSON.parse(await readFile(file, "utf8")) as unknown };
      } catch (error: unknown) {
        throw new DefinitionError(where(file), [`cannot read this token file: ${error instanceof Error ? error.message : String(error)}`]);
      }
    }),
  );
  const problems = validateTokenSets(sources);
  if (problems.length > 0) throw new DefinitionError(where(resolverFile), problems);
}

/** Resolve the aliases Terrazzo leaves inside youi-typed values (a focus ring's `{color.accent}`). */
function resolvedValue(token: TokenNormalized, set: Record<string, TokenNormalized>): unknown {
  return YOUI_TYPES.has(token.$type) ? resolveAliases(token.$value, (path) => set[path]?.$value) : token.$value;
}

/** The value as written, aliases kept. */
function sourceValue(token: TokenNormalized | undefined): unknown {
  const original = (token as { originalValue?: { $value?: unknown } } | undefined)?.originalValue;
  return original && "$value" in original ? original.$value : token?.$value;
}

export async function buildTokens(repoRoot: string, system: SystemConfig, output: OutputConfig, options: BuildOptions = {}): Promise<TokenBuild> {
  const resolverFile = join(repoRoot, system.tokens);
  const cwd = pathToFileURL(`${join(repoRoot, system.tokens, "..")}/`);
  const inputs = themeInputs(system);
  const prefix = output.cssVarPrefix;
  const resolverText = await readFile(resolverFile, "utf8");
  await validateSets(repoRoot, system, resolverText);

  const probe = defineConfig({ lint: { rules: {} } }, { cwd });
  const parsed = await parse([{ filename: pathToFileURL(resolverFile), src: resolverText }], { config: probe });
  unsafeNames(parsed.tokens, toPosix(relative(repoRoot, resolverFile)));
  const lightSet = parsed.resolver.apply(inputs.light);
  const darkSet = system.themeModifier ? parsed.resolver.apply(inputs.dark) : lightSet;
  const darkIds = Object.keys(lightSet).filter((id) => !YOUI_TYPES.has(lightSet[id]!.$type) && differs(lightSet[id]!, darkSet[id]));
  const tokens = resolvedTokens(lightSet, darkSet);

  // Springs and focus rings, which Terrazzo drops, plus the component state variables.
  const declare = (vars: ReadonlyArray<[string, string]>): string => vars.map(([name, value]) => `  ${name}: ${value};`).join("\n");
  const youiLight = youiTypeVariables(tokens, prefix, "light");
  const youiDarkAll = new Map(youiTypeVariables(tokens, prefix, "dark"));
  const youiDark = youiLight.filter(([name, value]) => youiDarkAll.has(name) && youiDarkAll.get(name) !== value).map(([name]) => [name, youiDarkAll.get(name)!] as [string, string]);
  const extraLight = declare([...youiLight, ...stateVariables(options.contracts ?? [], tokens, prefix)]);
  const extraDark = declare(youiDark);
  const withExtra = (contents: string, extra: string): string => (extra ? `${contents.trimEnd()}\n${extra}` : contents);

  const variableName = (token: TokenNormalized): string => `--${prefix}-${cssNameOf(token)}`;
  const permutations = [
    { input: inputs.light, prepare: (contents: string) => `:root {\n  color-scheme: light;\n${withExtra(indent(contents), extraLight)}\n}` },
    ...(system.themeModifier && darkIds.length > 0 ? [{ input: inputs.dark, include: darkIds, prepare: (contents: string) => wrapDark(withExtra(contents, extraDark), output) }] : []),
  ];
  // Hex-8 rounds alpha to 1/255 (.06 → 0f = .0588); colours and shadows go through cssValue,
  // which keeps translucent colours as exact `rgb(r g b / a)`. Aliases keep Terrazzo's var().
  // Terrazzo writes descriptions into comments and family names into quotes as they are, so both
  // are escaped here too: a second guard behind the token schema.
  const escaped = new WeakSet<object>();
  const transform = (token: TokenNormalized): string | undefined => {
    if (token.$description) token.$description = cssComment(token.$description);
    if (token.aliasOf) return undefined;
    if (token.$type === "color" || token.$type === "shadow") return cssValue(token.$type, token.$value);
    if (token.$type === "fontFamily") return familyList(token.$value).map(terrazzoFamily).join(", ");
    const value = token.$value as { fontFamily?: unknown } | undefined;
    if (token.$type === "typography" && value && !escaped.has(value) && !token.partialAliasOf?.fontFamily && value.fontFamily !== undefined) {
      value.fontFamily = familyList(value.fontFamily).map(escapedInside);
      escaped.add(value);
    }
    return undefined;
  };
  const config = defineConfig({ lint: { rules: {} }, plugins: [cssPlugin({ filename: "tokens.css", legacyHex: true, variableName, permutations, transform })] }, { cwd });
  const built = await build(parsed.tokens, { sources: parsed.sources, config, resolver: parsed.resolver });
  const terrazzoCss = built.outputFiles.find((f) => f.filename === "tokens.css")?.contents;
  if (typeof terrazzoCss !== "string") throw new Error("Terrazzo produced no tokens.css");
  // Only youi-typed values differ in dark: Terrazzo wrote no dark block to carry them.
  const css = system.themeModifier && darkIds.length === 0 && extraDark ? `${terrazzoCss.trimEnd()}\n\n${wrapDark(extraDark, output)}\n` : terrazzoCss;

  const header = generatedHeader(system, "css");
  const files: OutputFile[] = [];
  if (output.targets.includes("css-vars")) files.push({ path: "tokens.css", content: `${header}\n/* Built with Terrazzo (DTCG 2025.10 resolver). */\n${css.replace(/^\/\*[\s\S]*?\*\/\s*/, "")}` });
  if (output.targets.includes("tailwind-v4")) files.push({ path: "theme.css", content: renderTailwind(tokens, output, generatedHeader(system, "css")) });
  if (output.targets.includes("ts")) files.push({ path: "tokens.ts", content: renderTs(tokens, prefix, generatedHeader(system, "ts")) });
  if (output.targets.includes("react-native")) files.push({ path: "tokens.native.ts", content: renderNative(tokens, generatedHeader(system, "ts")) });
  return { system: system.id, version: system.version, prefix, tokens, files };
}

/** Every token, light and dark, with what it reads and its value as written. */
function resolvedTokens(lightSet: Record<string, TokenNormalized>, darkSet: Record<string, TokenNormalized>): ResolvedToken[] {
  return Object.values(lightSet)
    .map((token) => {
      const dark = darkSet[token.id];
      const source = { light: sourceValue(token), dark: sourceValue(dark ?? token) };
      // Terrazzo records no dependencies for the youi types: read them off the source.
      const dependsOn = YOUI_TYPES.has(token.$type) ? [...new Set([...aliasesIn(source.light), ...aliasesIn(source.dark)])].sort() : dependencyIds(token, dark);
      const darkAliasOf = dark?.aliasOf && dark.aliasOf !== token.aliasOf ? dark.aliasOf : undefined;
      return {
        id: token.id,
        type: token.$type,
        light: resolvedValue(token, lightSet),
        dark: dark ? resolvedValue(dark, darkSet) : resolvedValue(token, lightSet),
        ...(token.aliasOf ? { aliasOf: token.aliasOf } : {}),
        ...(darkAliasOf ? { darkAliasOf } : {}),
        ...(dependsOn.length > 0 ? { dependsOn } : {}),
        source,
        cssName: cssNameOf(token),
        ...(token.$description ? { description: token.$description } : {}),
      };
    })
    .sort((a, b) => a.id.localeCompare(b.id));
}
