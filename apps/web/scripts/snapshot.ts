/**
 * Builds everything the hub reads at runtime from a design-language checkout:
 *
 *   node scripts/snapshot.ts [--from <design-language-dir>] [--commit <sha>]
 *
 * - public/data/*.json: the system catalog (tokens, contracts, rules, narrative)
 *   and the usage maps, content-hashed so the browser can cache them forever.
 * - src/styles/generated/: the hub's own YouIyouX tokens, built by @youiyoux/tokens
 *   exactly like a product's tokens (tokens.css + Tailwind v4 theme.css).
 * - src/preview/generated/: Signal's scoped CSS variables and its owned component
 *   files, so element previews render the real components in the real tokens.
 *
 * `--from` defaults to the repository root. The @youiyoux packages are loaded from
 * that checkout, so the hub always reads definitions with the same code the CLI uses.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";

const APP = resolve(import.meta.dirname, "..");
const DATA_DIR = join(APP, "public/data");
const STYLES_DIR = join(APP, "src/styles/generated");
const PREVIEW_DIR = join(APP, "src/preview/generated");
const FIXTURES_DIR = join(APP, "fixtures");
const HASH_LENGTH = 10;
const SIGNAL_PREFIX = "so";
const HUB_PREFIX = "yx";

interface ResolvedToken {
  id: string;
  type: string;
  light: unknown;
  dark: unknown;
  aliasOf?: string;
  cssName: string;
  description?: string;
}

interface TokensModule {
  buildTokens(root: string, system: unknown, output: unknown): Promise<{ tokens: ResolvedToken[]; files: Array<{ path: string; content: string }> }>;
  cssValue(type: string, value: unknown): string;
}

interface CoreModule {
  loadDesignRepo(root: string): Promise<{ systems: Array<{ config: Record<string, unknown> & { id: string; name: string; version: string; description: string; design?: string; components: string; support: string[] }; components: Array<{ contract: Record<string, unknown> & { id: string; source: { file: string } }; dir: string }>; rules: Array<Record<string, unknown> & { id: string }> }> }>;
  OutputConfig: { parse(input: unknown): unknown };
  SystemConfig: { parse(input: unknown): unknown };
  ScanReport: { parse(input: unknown): unknown };
}

const hash = (text: string): string => createHash("sha256").update(text).digest("hex").slice(0, HASH_LENGTH);
const json = (value: unknown): string => `${JSON.stringify(value)}\n`;
const generated = (what: string): string => `/* @generated by apps/web/scripts/snapshot.ts from ${what}. Do not edit: run \`pnpm data\`. */\n`;

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function gitCommit(root: string): string | null {
  try {
    return execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

/** Follow aliasOf links to the token that holds the value: [self, …, source]. */
function aliasChain(token: ResolvedToken, byId: Map<string, ResolvedToken>): string[] {
  const chain = [token.id];
  let next = token.aliasOf;
  while (next && !chain.includes(next)) {
    chain.push(next);
    next = byId.get(next)?.aliasOf;
  }
  return chain;
}

function catalogTokens(system: string, tokens: ResolvedToken[], lib: TokensModule): unknown[] {
  const byId = new Map(tokens.map((t) => [t.id, t]));
  const elementId = (path: string): string => `youi:${system}/token/${path}`;
  return tokens.map((token) => ({
    id: elementId(token.id),
    path: token.id,
    group: token.id.split(".")[0],
    type: token.type,
    cssVar: `--${SIGNAL_PREFIX}-${token.cssName}`,
    light: lib.cssValue(token.type, token.light),
    dark: lib.cssValue(token.type, token.dark),
    ...(token.type === "typography" ? { lightValue: token.light } : {}),
    aliasChain: aliasChain(token, byId).map(elementId),
    ...(token.description ? { description: token.description } : {}),
  }));
}

/** The files a project vendors for this component: its own source plus the system's support files. */
function componentFiles(componentsRoot: string, sourceFile: string, support: string[]): Array<{ path: string; code: string }> {
  return [sourceFile, ...support].map((file) => ({ path: basename(file), code: readFileSync(join(componentsRoot, file), "utf8") }));
}

/** Signal's variables scoped to `.signal-scope`, light by default and dark under data-scheme. */
function scopedSignalCss(tokens: ResolvedToken[], lib: TokensModule): string {
  const decl = (scheme: "light" | "dark"): string =>
    tokens
      .filter((t) => t.type !== "typography")
      .map((t) => `  --${SIGNAL_PREFIX}-${t.cssName}: ${lib.cssValue(t.type, t[scheme])};`)
      .join("\n");
  return `${generated("the Signal tokens")}.signal-scope {\n  color-scheme: light;\n${decl("light")}\n}\n\n.signal-scope[data-scheme="dark"] {\n  color-scheme: dark;\n${decl("dark")}\n}\n`;
}

async function buildHubTokens(core: CoreModule, lib: TokensModule): Promise<void> {
  const system = core.SystemConfig.parse({
    id: "youiyoux",
    name: "YouIyouX",
    version: "0.1.0",
    description: "The hub's own design language.",
    tokens: "design/youiyoux.resolver.json",
    themeModifier: { name: "theme", light: "light", dark: "dark" },
  });
  const output = core.OutputConfig.parse({ cssVarPrefix: HUB_PREFIX, targets: ["css-vars", "tailwind-v4"] });
  const built = await lib.buildTokens(APP, system, output);
  rmSync(STYLES_DIR, { recursive: true, force: true });
  for (const file of built.files) write(join(STYLES_DIR, file.path), file.content);
}

function writeUsage(core: CoreModule): Array<{ project: string; file: string }> {
  const fixtures = readdirSync(FIXTURES_DIR).filter((f) => f.endsWith(".usage.json")).sort();
  return fixtures.map((name) => {
    const report = core.ScanReport.parse(JSON.parse(readFileSync(join(FIXTURES_DIR, name), "utf8"))) as { project: string };
    const text = json(report);
    const file = `${report.project}.usage.${hash(text)}.json`;
    write(join(DATA_DIR, file), text);
    return { project: report.project, file };
  });
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { from: { type: "string" }, commit: { type: "string" } } });
  const root = resolve(values.from ?? join(APP, "../.."));
  const load = async <T>(pkg: string): Promise<T> => (await import(pathToFileURL(join(root, "packages", pkg, "src/index.ts")).href)) as T;
  const core = await load<CoreModule>("core");
  const lib = await load<TokensModule>("tokens");

  const repo = await core.loadDesignRepo(root);
  const signal = repo.systems.find((s) => s.config.id === "signal");
  if (!signal) throw new Error(`no "signal" system in ${root}/youi.config.json`);
  const output = core.OutputConfig.parse({ cssVarPrefix: SIGNAL_PREFIX });
  const built = await lib.buildTokens(root, signal.config, output);
  const componentsRoot = join(root, signal.config.components);

  rmSync(DATA_DIR, { recursive: true, force: true });
  rmSync(PREVIEW_DIR, { recursive: true, force: true });

  const catalog = {
    schema: "youiyoux.catalog/v1",
    system: {
      id: signal.config.id,
      name: signal.config.name,
      version: signal.config.version,
      description: signal.config.description,
      cssPrefix: SIGNAL_PREFIX,
      design: signal.config.design ? readFileSync(join(root, signal.config.design), "utf8") : "",
    },
    tokens: catalogTokens(signal.config.id, built.tokens, lib),
    components: signal.components.map(({ contract }) => ({ contract, files: componentFiles(componentsRoot, contract.source.file, signal.config.support) })),
    rules: signal.rules,
  };
  const catalogText = json(catalog);
  const catalogFile = `${signal.config.id}.catalog.${hash(catalogText)}.json`;
  write(join(DATA_DIR, catalogFile), catalogText);
  const usage = writeUsage(core);

  const commit = values.commit ?? gitCommit(root);
  write(join(DATA_DIR, "manifest.json"), `${JSON.stringify({ schema: "youiyoux.manifest/v1", source: { commit }, systems: [{ id: signal.config.id, catalog: catalogFile, usage }] }, null, 2)}\n`);

  write(join(PREVIEW_DIR, "signal-scope.css"), scopedSignalCss(built.tokens, lib));
  const files = new Set([...signal.components.map((c) => c.contract.source.file), ...signal.config.support]);
  for (const file of files) {
    write(join(PREVIEW_DIR, "signal", basename(file)), `// @generated from design-language components/${file} by apps/web/scripts/snapshot.ts. Do not edit.\n${readFileSync(join(componentsRoot, file), "utf8")}`);
  }

  await buildHubTokens(core, lib);
  process.stdout.write(`snapshot from ${relative(APP, root) || "."} @ ${commit ?? "unknown"}: ${catalog.tokens.length} tokens, ${catalog.components.length} components, ${catalog.rules.length} rules; ${usage.length} usage map(s)\n`);
}

await main();
